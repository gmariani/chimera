function table(text: string, sized: boolean): Template[] {
    return text.split(/\s+/).map((row, id) => {
        const parts = row.split(':');
        return sized ? { id, name: parts[0], width: Number(parts[1]), height: Number(parts[2]), theaters: parts[3] } : { id, name: parts[0], theaters: parts[1] };
    });
}

export const TD_TEMPLATES = table(TD, true);
export const RA_TEMPLATES = table(RA, false);

/** The file extension each theater's tile sets use. */
export const THEATER_EXTENSIONS: Record<'td' | 'ra', Record<string, string>> = {
    td: { D: 'des', J: 'jun', T: 'tem', W: 'win' },
    ra: { I: 'int', S: 'sno', T: 'tem' },
};

/** Every tile set file name: each template in each theater it belongs to. */
export function templateFileNames(): string[] {
    const names: string[] = [];
    for (const [game, templates] of [
        ['td', TD_TEMPLATES],
        ['ra', RA_TEMPLATES],
    ] as const) {
        for (const t of templates) for (const letter of t.theaters) names.push(`${t.name.toLowerCase()}.${THEATER_EXTENSIONS[game][letter]}`);
    }
    return names;
}

/** The template a tile set file belongs to, from its name. */
export function templateOf(fileName: string | null, game: 'td' | 'ra'): Template | null {
    const match = fileName?.toLowerCase().match(/^(.+)\.([a-z]+)$/);
    if (!match) return null;
    const [, base, ext] = match;
    const letter = Object.entries(THEATER_EXTENSIONS[game]).find(([, e]) => e === ext)?.[0];
    const templates = game === 'td' ? TD_TEMPLATES : RA_TEMPLATES;
    return (letter && templates.find((t) => t.name.toLowerCase() === base && t.theaters.includes(letter))) || null;
}
